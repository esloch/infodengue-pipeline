"""Review generated scientific SQL before the upstream psql application."""

from __future__ import annotations

import os
import re
import subprocess  # nosec B404
import sys

from pathlib import Path

import psycopg

from infodengue_pipeline.production.target import (
    ANALYSIS_E2E_DATABASE,
    ANALYSIS_E2E_HOST,
    ANALYSIS_E2E_ROLE,
    RESTORE_EVIDENCE_SQL,
)

TABLES = {
    'output_dengue.sql': ('Historico_alerta', 'alertas_unicos'),
    'output_chik.sql': ('Historico_alerta_chik', 'alertas_unicos_chik'),
}
STATEMENT = re.compile(
    r'\AINSERT\s+INTO\s+"Municipio"\."(?P<table>[^"]+)"\s*'
    r'\((?P<columns>[^)]+)\)\s+VALUES\s*\((?P<values>.*)\)\s+'
    r'ON\s+CONFLICT\s+ON\s+CONSTRAINT\s+(?P<constraint>\w+)\s+'
    r'DO\s+UPDATE\s+SET\s+(?P<updates>.+)\Z',
    re.DOTALL,
)
ASSIGNMENT = re.compile(
    r'\A\s*("?[A-Za-z_][A-Za-z_0-9]*"?)\s*=\s*'
    r'excluded\.\1\s*\Z',
)
LITERAL_VALUES = re.compile(
    r"\A\s*(?:NULL|TRUE|FALSE|[-+]?\d+(?:\.\d+)?(?:e[-+]?\d+)?|'(?:[^']|'')*')"
    r"(?:\s*,\s*(?:NULL|TRUE|FALSE|[-+]?\d+(?:\.\d+)?(?:e[-+]?\d+)?|'(?:[^']|'')*'))*"
    r'\s*\Z',
    re.IGNORECASE | re.DOTALL,
)


class SqlReviewError(ValueError):
    """Generated SQL or its destination violates the rehearsal contract."""


def statements(path: Path) -> list[str]:
    """Split SQL at semicolons outside quoted SQL string literals."""
    if not path.is_file() or path.stat().st_size == 0:
        raise SqlReviewError('generated SQL missing')
    if path.stat().st_size > 512 * 1024 * 1024:
        raise SqlReviewError('generated SQL exceeds review size limit')
    data = path.read_text(encoding='utf-8')
    found: list[str] = []
    current: list[str] = []
    quoted = False
    position = 0
    while position < len(data):
        char = data[position]
        if char == "'":
            if (
                quoted
                and position + 1 < len(data)
                and data[position + 1] == "'"
            ):
                current.extend((char, char))
                position += 2
                continue
            quoted = not quoted
        if char == ';' and not quoted:
            statement = ''.join(current).strip()
            if not statement:
                raise SqlReviewError('empty SQL statement')
            found.append(statement)
            current.clear()
        else:
            current.append(char)
        position += 1
    if quoted or ''.join(current).strip() or not found:
        raise SqlReviewError('unterminated generated SQL')
    return found


def review_sql(path: Path, output_root: Path) -> int:
    """Allow only current-run historical upserts generated by AlertTools."""
    expected = TABLES.get(path.name)
    if (
        expected is None
        or path.resolve().parent != (output_root / 'sql').resolve()
    ):
        raise SqlReviewError('unexpected SQL path')
    count = 0
    for sql in statements(path):
        match = STATEMENT.fullmatch(sql)
        if match is None or (match['table'], match['constraint']) != expected:
            raise SqlReviewError('unexpected SQL statement or table')
        columns = [item.strip() for item in match['columns'].split(',')]
        if columns[0] != '"SE"' or 'municipio_geocodigo' not in columns:
            raise SqlReviewError('missing bounded historical key columns')
        if re.match(r'\A\s*\d{6}\s*,', match['values']) is None:
            raise SqlReviewError('invalid epidemiological week value')
        if LITERAL_VALUES.fullmatch(match['values']) is None:
            raise SqlReviewError('unexpected SQL value expression')
        updates = match['updates'].split(',')
        if not updates or not all(
            ASSIGNMENT.fullmatch(item) for item in updates
        ):
            raise SqlReviewError('unexpected conflict update')
        count += 1
    return count


def _validated_arguments(argv: list[str]) -> tuple[str, str, str, Path]:
    """Accept only the exact psql shape emitted by the pinned Makim task."""
    if len(argv) != 12 or argv[:2] != ['-v', 'ON_ERROR_STOP=1']:
        raise SqlReviewError('unexpected psql arguments')
    if [argv[i] for i in (2, 4, 6, 8)] != ['-h', '-p', '-U', '-d']:
        raise SqlReviewError('unexpected psql arguments')
    if argv[10] != '-f' or argv[5] != '5432':
        raise SqlReviewError('unexpected psql arguments')
    if (argv[3], argv[7], argv[9]) != (
        ANALYSIS_E2E_HOST,
        ANALYSIS_E2E_ROLE,
        ANALYSIS_E2E_DATABASE,
    ):
        raise SqlReviewError(
            'SQL destination is not the isolated staging clone'
        )
    return argv[3], argv[5], argv[7], Path(argv[11])


def review_and_apply(argv: list[str]) -> int:
    """Review the file and live clone identity, then call the real psql."""
    if (
        os.environ.get('INFODENGUE_PIPELINE_ENVIRONMENT') != 'prod'
        or os.environ.get('INFODENGUE_PIPELINE_ANALYSIS_LOAD') != 'true'
    ):
        raise SqlReviewError('production analysis SQL review gate is inactive')
    host, port, role, path = _validated_arguments(argv)
    root_value = os.environ.get('ALERTA_OUT_DIR')
    digest = os.environ.get(
        'INFODENGUE_PIPELINE_ANALYSIS_STAGING_BACKUP_SHA256'
    )
    password = os.environ.get('PGPASSWORD')
    if not root_value or not digest or not password or len(digest) != 64:
        raise SqlReviewError('backup or output evidence is missing')
    # libpq accepts connection overrides from the environment even when psql
    # receives explicit -h/-U/-d arguments (notably PGHOSTADDR and PGSERVICE).
    for name in tuple(os.environ):
        if name.startswith('PG') and name != 'PGPASSWORD':
            os.environ.pop(name)
    count = review_sql(path, Path(root_value))
    try:
        with psycopg.connect(
            host=host,
            port=int(port),
            dbname=ANALYSIS_E2E_DATABASE,
            user=role,
            password=password,
            connect_timeout=10,
        ) as connection:
            with connection.cursor() as cursor:
                cursor.execute('SELECT current_database(), current_user')
                if cursor.fetchone() != (ANALYSIS_E2E_DATABASE, role):
                    raise SqlReviewError('effective SQL destination differs')
                cursor.execute(
                    RESTORE_EVIDENCE_SQL.replace(':environment', '%s'),
                    ('staging',),
                )
                if cursor.fetchone() != (digest,):
                    raise SqlReviewError('restored backup identity differs')
                cursor.execute(
                    'SELECT rolsuper, rolcreatedb, rolcreaterole, '
                    'rolreplication, rolbypassrls FROM pg_roles '
                    'WHERE rolname = current_user'
                )
                flags = cursor.fetchone()
                if flags is None or any(flags):
                    raise SqlReviewError(
                        'analysis role has elevated privileges'
                    )
                cursor.execute(
                    'SELECT EXISTS (SELECT 1 FROM pg_auth_members '
                    'WHERE member = (SELECT oid FROM pg_roles '
                    'WHERE rolname = current_user))'
                )
                if cursor.fetchone() != (False,):
                    raise SqlReviewError('analysis role has role memberships')
                cursor.execute(
                    'SELECT bool_and(has_table_privilege(current_user, '
                    "format('%I.%I', 'Municipio', table_name), 'INSERT') "
                    'AND has_table_privilege(current_user, '
                    "format('%I.%I', 'Municipio', table_name), 'UPDATE') "
                    'AND NOT has_table_privilege(current_user, '
                    "format('%I.%I', 'Municipio', table_name), 'DELETE') "
                    'AND NOT has_table_privilege(current_user, '
                    "format('%I.%I', 'Municipio', table_name), 'TRUNCATE')) "
                    "FROM unnest(ARRAY['Historico_alerta', "
                    "'Historico_alerta_chik', 'Historico_alerta_zika']) "
                    'AS names(table_name)'
                )
                if cursor.fetchone() != (True,):
                    raise SqlReviewError(
                        'analysis role table grants differ from contract'
                    )
                cursor.execute(
                    'SELECT NOT EXISTS (SELECT 1 FROM pg_class c '
                    'JOIN pg_namespace n ON n.oid = c.relnamespace '
                    "WHERE c.relkind IN ('r', 'p', 'v', 'm') AND NOT ("
                    "n.nspname = 'Municipio' AND c.relname IN "
                    "('Historico_alerta', 'Historico_alerta_chik', "
                    "'Historico_alerta_zika')) "
                    "AND (has_table_privilege(current_user, c.oid, 'INSERT') "
                    "OR has_table_privilege(current_user, c.oid, 'UPDATE') "
                    "OR has_table_privilege(current_user, c.oid, 'DELETE') "
                    "OR has_table_privilege(current_user, c.oid, 'TRUNCATE')))"
                )
                if cursor.fetchone() != (True,):
                    raise SqlReviewError(
                        'analysis role can modify other tables'
                    )
                cursor.execute(
                    'SELECT NOT has_database_privilege(current_user, '
                    "current_database(), 'CREATE') AND NOT EXISTS ("
                    'SELECT 1 FROM pg_namespace n WHERE '
                    "has_schema_privilege(current_user, n.oid, 'CREATE'))"
                )
                if cursor.fetchone() != (True,):
                    raise SqlReviewError('analysis role can create DB objects')
                cursor.execute(
                    'SELECT EXISTS (SELECT 1 FROM pg_class c '
                    'WHERE c.relowner = (SELECT oid FROM pg_roles '
                    'WHERE rolname = current_user)) OR EXISTS '
                    '(SELECT 1 FROM pg_namespace n WHERE n.nspowner = '
                    '(SELECT oid FROM pg_roles WHERE rolname = current_user)) '
                    'OR EXISTS (SELECT 1 FROM pg_database d WHERE '
                    'd.datname = current_database() AND d.datdba = '
                    '(SELECT oid FROM pg_roles WHERE rolname = current_user))'
                )
                if cursor.fetchone() != (False,):
                    raise SqlReviewError('analysis role owns DB objects')
    except SqlReviewError:
        raise
    except Exception as exc:
        raise SqlReviewError('SQL destination probe failed') from exc
    print(
        f'[OK] pre-application SQL review: {path.name}, rows={count}',
        flush=True,
    )
    result = subprocess.run(  # nosec B603
        ['/opt/conda/envs/alertadengueanalise/bin/psql', *argv], check=False
    )
    return result.returncode


def main() -> int:
    """Exit with a sanitized refusal if review fails."""
    try:
        return review_and_apply(sys.argv[1:])
    except SqlReviewError as exc:
        print(f'production analysis SQL refused: {exc}', file=sys.stderr)
        return 75
